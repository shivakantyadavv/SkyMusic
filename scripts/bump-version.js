import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
export const ROOT_DIR = path.resolve(__dirname, "..");

const PATHS = {
  pkg: path.join(ROOT_DIR, "package.json"),
  tauriConf: path.join(ROOT_DIR, "src-tauri", "tauri.conf.json"),
  cargoToml: path.join(ROOT_DIR, "src-tauri", "Cargo.toml"),
  tauriProps: path.join(
    ROOT_DIR,
    "src-tauri",
    "gen",
    "android",
    "app",
    "tauri.properties"
  ),
  buildGradle: path.join(
    ROOT_DIR,
    "src-tauri",
    "gen",
    "android",
    "app",
    "build.gradle.kts"
  ),
};

export function computeNextVersion(currentSemver) {
  const parts = currentSemver
    .replace(/^v/i, "")
    .split(".")
    .map((n) => parseInt(n, 10) || 0);
  let major = parts[0] || 1;
  let minor = parts[1] || 0;

  if (minor >= 9) {
    major += 1;
    minor = 0;
  } else {
    minor += 1;
  }

  return {
    semver: `${major}.${minor}.0`,
    short: `${major}.${minor}`,
    tag: `v${major}.${minor}`,
    androidVersionCode: major * 1_000_000 + minor * 1_000,
  };
}

export function getCurrentVersion() {
  const pkg = JSON.parse(fs.readFileSync(PATHS.pkg, "utf8"));
  const parts = pkg.version.split(".");
  return {
    semver: pkg.version,
    short: `${parts[0]}.${parts[1]}`,
    tag: `v${parts[0]}.${parts[1]}`,
  };
}

export function applyVersionBump({ dryRun = false, targetVersion = null } = {}) {
  const pkg = JSON.parse(fs.readFileSync(PATHS.pkg, "utf8"));
  const next = targetVersion
    ? (() => {
        const clean = targetVersion.replace(/^v/i, "").split(".");
        const major = parseInt(clean[0], 10) || 1;
        const minor = parseInt(clean[1], 10) || 0;
        return {
          semver: `${major}.${minor}.0`,
          short: `${major}.${minor}`,
          tag: `v${major}.${minor}`,
          androidVersionCode: major * 1_000_000 + minor * 1_000,
        };
      })()
    : computeNextVersion(pkg.version);

  if (dryRun) {
    return { previous: pkg.version, next };
  }

  // 1. package.json
  pkg.version = next.semver;
  fs.writeFileSync(PATHS.pkg, `${JSON.stringify(pkg, null, 2)}\n`, "utf8");

  // 2. src-tauri/tauri.conf.json
  const tauriConf = JSON.parse(fs.readFileSync(PATHS.tauriConf, "utf8"));
  tauriConf.version = next.semver;
  fs.writeFileSync(
    PATHS.tauriConf,
    `${JSON.stringify(tauriConf, null, 2)}\n`,
    "utf8"
  );

  // 3. src-tauri/Cargo.toml
  const cargoRaw = fs.readFileSync(PATHS.cargoToml, "utf8");
  const updatedCargo = cargoRaw.replace(
    /^version\s*=\s*"[^"]+"/m,
    `version = "${next.semver}"`
  );
  fs.writeFileSync(PATHS.cargoToml, updatedCargo, "utf8");

  // 4. src-tauri/gen/android/app/tauri.properties
  const propsContent = [
    "// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.",
    `tauri.android.versionName=${next.semver}`,
    `tauri.android.versionCode=${next.androidVersionCode}`,
    "",
  ].join("\n");
  fs.writeFileSync(PATHS.tauriProps, propsContent, "utf8");

  // 5. src-tauri/gen/android/app/build.gradle.kts default fallbacks
  if (fs.existsSync(PATHS.buildGradle)) {
    let gradle = fs.readFileSync(PATHS.buildGradle, "utf8");
    gradle = gradle
      .replace(
        /tauriProperties\.getProperty\("tauri\.android\.versionCode",\s*"\d+"\)/,
        `tauriProperties.getProperty("tauri.android.versionCode", "${next.androidVersionCode}")`
      )
      .replace(
        /tauriProperties\.getProperty\("tauri\.android\.versionName",\s*"[^"]+"\)/,
        `tauriProperties.getProperty("tauri.android.versionName", "${next.semver}")`
      );
    fs.writeFileSync(PATHS.buildGradle, gradle, "utf8");
  }

  return { previous: pkg.version, next };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const dryRun = args.includes("--dry-run");
  const setIdx = args.indexOf("--set");
  const targetVersion = setIdx >= 0 ? args[setIdx + 1] : null;
  const current = getCurrentVersion();
  const result = applyVersionBump({ dryRun, targetVersion });
  console.log(
    `${dryRun ? "[DRY RUN] " : ""}Version ${current.semver} -> ${result.next.semver} (${result.next.tag}, Android versionCode=${result.next.androidVersionCode})`
  );
}
